pub fn by_id(id: &str) -> usize {
    LANGS.iter().position(|l| l.id == id).unwrap_or(0)
}

/// Picks a language from the file name, then from a shebang or XML/HTML prolog.
pub fn detect(name: &str, head: &[u8]) -> usize {
    let lower = name.to_ascii_lowercase();
    let file = lower.rsplit(['\\', '/']).next().unwrap_or(&lower);
    if let Some(i) = LANGS.iter().position(|l| l.files.contains(&file)) {
        return i;
    }
    if let Some((_, ext)) = file.rsplit_once('.') {
        if let Some(i) = LANGS.iter().position(|l| l.exts.contains(&ext)) {
            return i;
        }
    }
    let head = std::string::String::from_utf8_lossy(&head[..head.len().min(256)]);
    let first = head.lines().next().unwrap_or("").trim();
    if let Some(sb) = first.strip_prefix("#!") {
        for (needle, id) in [("python", "python"), ("bash", "shell"), ("/sh", "shell"), ("zsh", "shell"), ("node", "javascript"), ("ruby", "ruby"), ("perl", "perl"), ("pwsh", "powershell"), ("lua", "lua")] {
            if sb.contains(needle) {
                return by_id(id);
            }
        }
    }
    if first.starts_with("<?xml") {
        return by_id("xml");
    }
    let lower_head = first.to_ascii_lowercase();
    if lower_head.starts_with("<!doctype html") || lower_head.starts_with("<html") {
        return by_id("html");
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_by_name_and_content() {
        assert_eq!(LANGS[detect("C:\\x\\main.rs", b"")].id, "rust");
        assert_eq!(LANGS[detect("notes.MD", b"")].id, "markdown");
        assert_eq!(LANGS[detect("Makefile", b"")].id, "makefile");
        assert_eq!(LANGS[detect("CMakeLists.txt", b"")].id, "cmake");
        assert_eq!(LANGS[detect("script", b"#!/usr/bin/env python3\n")].id, "python");
        assert_eq!(LANGS[detect("x", b"<?xml version=\"1.0\"?>")].id, "xml");
        assert_eq!(LANGS[detect("readme", b"hello")].id, "text");
    }

    #[test]
    fn ids_are_unique_and_lexers_exist() {
        let mut ids: Vec<_> = LANGS.iter().map(|l| l.id).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), LANGS.len());
    }
}
