use std::fs;
use std::path::{Path, PathBuf};

fn cxx_files(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "cxx"))
        .collect();
    v.sort();
    v
}

/// Turns every `#define NAME <integer>` in a Scintilla header into a Rust
/// constant, so the message and style numbers come straight from the source.
fn consts_from_header(path: &Path, out: &mut String) {
    let text = fs::read_to_string(path).unwrap();
    for line in text.lines() {
        let mut it = line.split_whitespace();
        if it.next() != Some("#define") {
            continue;
        }
        let (Some(name), Some(val)) = (it.next(), it.next()) else { continue };
        if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') || name.starts_with("SCINTILLA") {
            continue;
        }
        let parsed = if let Some(hex) = val.strip_prefix("0x") {
            i64::from_str_radix(hex, 16).ok()
        } else {
            val.parse::<i64>().ok()
        };
        if let Some(v) = parsed {
            out.push_str(&format!("pub const {name}: i64 = {v};\n"));
        }
    }
}

fn main() {
    let sci = Path::new("vendor/scintilla");
    let lex = Path::new("vendor/lexilla");
    println!("cargo:rerun-if-changed=vendor");
    println!("cargo:rerun-if-changed=native");
    println!("cargo:rerun-if-changed=nib.manifest");
    println!("cargo:rerun-if-changed=nib.rc");

    let mut b = cc::Build::new();
    b.cpp(true)
        .std("c++17")
        .flag_if_supported("/EHsc")
        .flag_if_supported("/utf-8")
        .flag_if_supported("/MP")
        .warnings(false)
        .define("UNICODE", None)
        .define("_UNICODE", None)
        .define("NDEBUG", None)
        .define("NO_CXX11_REGEX", None)
        .include(sci.join("include"))
        .include(sci.join("src"))
        .include(sci.join("win32"))
        .include(lex.join("include"))
        .include(lex.join("lexlib"));
    for f in cxx_files(&sci.join("src")).into_iter().chain(cxx_files(&sci.join("win32"))) {
        b.file(f);
    }
    for f in cxx_files(&lex.join("lexlib")).into_iter().chain(cxx_files(&lex.join("lexers"))) {
        b.file(f);
    }
    b.file("native/nib_lexers.cxx");
    b.compile("scintilla");

    for lib in ["user32", "gdi32", "imm32", "ole32", "oleaut32", "advapi32", "uuid", "msimg32"] {
        println!("cargo:rustc-link-lib={lib}");
    }

    let mut consts = String::from("// Generated by build.rs from Scintilla.h and SciLexer.h.\n");
    consts_from_header(&sci.join("include/Scintilla.h"), &mut consts);
    consts_from_header(&lex.join("include/SciLexer.h"), &mut consts);
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("sci_consts.rs");
    fs::write(out, consts).unwrap();

    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        let manifest = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("nib.manifest");
        println!("cargo:rustc-link-arg-bin=nib=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg-bin=nib=/MANIFESTINPUT:{}", manifest.display());
    }
}
